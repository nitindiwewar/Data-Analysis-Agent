"""
15-Query Evaluation Benchmark Suite in Python
Automated evaluation covering schema linking, SQL syntax correctness, and execution validation.
"""

import time
from typing import Dict, Any, List
from backend.agent_orchestrator import process_data_analyst_question

BENCHMARK_CASES = [
    {"id": "q1", "category": "Top-N Ranking", "question": "What are the top 5 selling products by total revenue?"},
    {"id": "q2", "category": "Aggregation", "question": "What is the total revenue and profit across all orders?"},
    {"id": "q3", "category": "Multi-Table Join", "question": "Show revenue generated by each customer company"},
    {"id": "q4", "category": "Regional Analysis", "question": "Compare sales revenue across all regions"},
    {"id": "q5", "category": "Threshold Filtering", "question": "Which products have inventory below 50 units?"},
    {"id": "q6", "category": "Hinglish Synonyms", "question": "Kis product se sabse zyada munafa aur kamai hui?"},
    {"id": "q7", "category": "Customer Segmentation", "question": "List all Enterprise customers in Bangalore"},
    {"id": "q8", "category": "Date Trend", "question": "Monthly sales performance in 2024"},
    {"id": "q9", "category": "Discount Analysis", "question": "Show orders with discount percent greater than 0%"},
    {"id": "q10", "category": "Category Breakdown", "question": "Total quantity of Laptops sold"},
    {"id": "q11", "category": "Single Item Query", "question": "Show total sales for MacBook Pro 16"},
    {"id": "q12", "category": "Payment Method", "question": "Total orders paid via Bank Transfer"},
    {"id": "q13", "category": "Average Metric", "question": "What is the average discount given on orders?"},
    {"id": "q14", "category": "Low Performer", "question": "Which product generated the least revenue?"},
    {"id": "q15", "category": "Multi-Entity Hinglish", "question": "Maharashtra region me kitna profit hua?"}
]

async def run_full_benchmark_suite() -> Dict[str, Any]:
    t0 = time.time()
    results = []
    passed_count = 0

    for case in BENCHMARK_CASES:
        t_case = time.time()
        res = await process_data_analyst_question(case["question"])
        has_sql = bool(res.get("sql"))
        is_valid = res.get("validation", {}).get("isValid", False)
        has_data = res.get("result", {}).get("rowCount", 0) > 0
        is_passed = has_sql and is_valid and has_data

        if is_passed:
            passed_count += 1

        results.append({
            "testId": case["id"],
            "category": case["category"],
            "question": case["question"],
            "passed": is_passed,
            "generatedSql": res.get("sql", ""),
            "durationMs": round((time.time() - t_case) * 1000, 2),
            "rowCount": res.get("result", {}).get("rowCount", 0)
        })

    total_tests = len(BENCHMARK_CASES)
    accuracy_score = round((passed_count / total_tests) * 100, 1)

    return {
        "suiteName": "Automated SQL Accuracy Benchmark Suite",
        "totalTests": total_tests,
        "passedTests": passed_count,
        "failedTests": total_tests - passed_count,
        "accuracyScore": accuracy_score,
        "overallAccuracy": accuracy_score,
        "totalExecutionTimeMs": round((time.time() - t0) * 1000, 2),
        "results": results
    }
